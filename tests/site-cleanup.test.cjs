const assert=require('node:assert/strict');
const fs=require('node:fs');
const cp=require('node:child_process');
const read=p=>fs.readFileSync(p,'utf8').replace(/\r\n/g,'\n');
const old=p=>cp.execFileSync('git',['show',`HEAD:${p}`],{encoding:'utf8'});
const home=read('index.html'),baseline=old('index.html'),cloud=read('cloudwards/index.html');
const section=(html,id)=>html.match(new RegExp('<section[^>]*id="'+id+'"[\\s\\S]*?<\\/section>'))[0];
for(const id of ['about','work'])assert.equal(section(home,id),section(baseline,id));
const offers=section(home,'ways-to-work'),previousOffers=section(baseline,'ways-to-work');
const price=html=>[...html.matchAll(/class="ways-to-work-price">([^<]+)/g)].map(m=>m[1]);
assert.deepEqual(price(offers),price(previousOffers));
const lists=html=>[...html.matchAll(/<ul>[\s\S]*?<\/ul>/g)].map(m=>m[0]);
assert.deepEqual(lists(offers),lists(previousOffers),'all offer inclusions and responsibilities retained');
assert.equal(offers.match(/<details[\s\S]*?<\/details>/)[0],previousOffers.match(/<details[\s\S]*?<\/details>/)[0]);
const conditions=html=>[...html.matchAll(/<p class="ways-to-work-(?:credit|qualification|sprint-note)">[\s\S]*?<\/p>/g)].map(m=>m[0]);
assert.deepEqual(conditions(offers),conditions(previousOffers));
assert(home.includes('id="care" aria-labelledby="website-care-title"'));
assert(!home.includes('Support Beyond Launch'));
assert(!/<a href="#contact"[^>]*>Learn More/.test(home));
for(const text of ['Discuss Website Design','Discuss Website Development','Discuss Website Care'])assert(home.includes(text));
assert(home.includes('type="image/svg+xml" href="/assets/mvtj-logo-primary.svg"'));
const process=section(home,'process');assert.deepEqual([...process.matchAll(/<h3>(.*?)<\/h3>/g)].map(m=>m[1]),['Discover','Define','Design &amp; Build','Launch &amp; Care']);
assert.deepEqual([...process.matchAll(/<div class="step-num">(.*?)<\/div>/g)].map(m=>m[1]),['01','02','03','04']);
assert.deepEqual([...process.matchAll(/<svg[\s\S]*?<\/svg>/g)].map(m=>m[0]),[...section(baseline,'process').matchAll(/<svg[\s\S]*?<\/svg>/g)].map(m=>m[0]));
assert.equal(home.match(/<nav[\s\S]*?<\/nav>/)[0],baseline.match(/<nav[\s\S]*?<\/nav>/)[0]);
assert(home.includes('https://calendly.com/max-tijerino/30min')&&home.includes('https://wa.me/35794338222'));
assert(read('founder/index.html').includes('<a href="/privacy/">Privacy Policy</a>'), 'required founder Privacy Policy link remains present');
assert.equal(read('founder/index.html'),old('founder/index.html').replace(/\r\n/g,'\n'));
for(const url of ['https://etalenta.me/max-tijerino','https://www.encast.pro/profile/53925/max-tijerino','https://www.imdb.com/name/nm5947252/','https://showreel.etalenta.eu/max-tijerino/startplaylist/340733'])assert(read('founder/index.html').includes(url));
assert.equal((cloud.match(/<strong>Role &amp; Services<\/strong>/g)||[]).length,1);assert(!cloud.includes('<strong>Role</strong>')&&!cloud.includes('<strong>Services</strong>'));
